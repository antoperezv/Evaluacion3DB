-- TABLA: T_PUNTO_ACOPIO
-- ID_PUNTO autoincrementable (IDENTITY): inicia en 10, incrementa de 1 en 1
CREATE TABLE T_PUNTO_ACOPIO (
    ID_PUNTO                   NUMBER GENERATED ALWAYS AS IDENTITY
                               (START WITH 10 INCREMENT BY 1) NOT NULL,
    NOMBRE_PUNTO               VARCHAR2(80) NOT NULL,
    TIPO_PUNTO                 VARCHAR2(20) NOT NULL,
    DIRECCION                  VARCHAR2(120) NOT NULL,
    COMUNA                     VARCHAR2(50) NOT NULL,
    CAPACIDAD_M3               NUMBER(6,1) NOT NULL,
    CONSTRAINT PK_PUNTO_ACOPIO PRIMARY KEY (ID_PUNTO),
    CONSTRAINT CK_PUNTO_ACOPIO_TIPO_PUNTO
        CHECK (TIPO_PUNTO IN ('Punto Limpio', 'Centro de Acopio', 'Contenedor Verde'))
);

-- TABLA: T_LOTE_RECOLECCION
CREATE TABLE T_LOTE_RECOLECCION (
    NRO_LOTE                   NUMBER NOT NULL,
    FK_ID_PUNTO                NUMBER NOT NULL,
    FK_ID_MATERIALIDAD         NUMBER NOT NULL,
    FK_ID_TRANSPORTISTA        NUMBER NOT NULL,
    FECHA_RECOLECCION          DATE NOT NULL,
    PESO_BRUTO_KG              NUMBER(10,2) NOT NULL,
    PORC_CONTAMINACION         NUMBER(5,2) NOT NULL,
    ESTADO_LOTE                VARCHAR2(15) NOT NULL,
    CONSTRAINT PK_LOTE_RECOLECCION PRIMARY KEY (NRO_LOTE),
    CONSTRAINT FK_LOTE_RECOLEC_PUNTO_ACOPIO FOREIGN KEY (FK_ID_PUNTO)
        REFERENCES T_PUNTO_ACOPIO (ID_PUNTO),
    CONSTRAINT FK_LOTE_RECOLEC_MATERIALIDAD FOREIGN KEY (FK_ID_MATERIALIDAD)
        REFERENCES T_MATERIALIDAD (ID_MATERIALIDAD),
    CONSTRAINT FK_LOTE_RECOLEC_TRANSPORTISTA FOREIGN KEY (FK_ID_TRANSPORTISTA)
        REFERENCES T_TRANSPORTISTA (ID_TRANSPORTISTA),
    CONSTRAINT CK_LOTE_RECOLEC_ESTADO_LOTE
        CHECK (ESTADO_LOTE IN ('Recibido', 'Clasificado', 'Rechazado')),
    CONSTRAINT CK_LOTE_RECOLEC_PORC_CONTAMIN
        CHECK (PORC_CONTAMINACION BETWEEN 0 AND 100),
    CONSTRAINT CK_LOTE_RECOLEC_PESO_BRUTO
        CHECK (PESO_BRUTO_KG > 0)
);

-- TABLA: T_SUBPRODUCTO
CREATE TABLE T_SUBPRODUCTO (
    ID_SUBPRODUCTO             NUMBER NOT NULL,
    NOMBRE_SUBPRODUCTO         VARCHAR2(60) NOT NULL,
    FK_ID_MATERIALIDAD         NUMBER NOT NULL,
    PRECIO_TONELADA            NUMBER(10) NOT NULL,
    CONSTRAINT PK_SUBPRODUCTO PRIMARY KEY (ID_SUBPRODUCTO),
    CONSTRAINT UN_SUBPRODUCTO_NOMBRE_SUBPRODU UNIQUE (NOMBRE_SUBPRODUCTO),
    CONSTRAINT FK_SUBPRODUCTO_MATERIALIDAD FOREIGN KEY (FK_ID_MATERIALIDAD)
        REFERENCES T_MATERIALIDAD (ID_MATERIALIDAD)
);

-- TABLA: T_TRANSFORMACION_LOTE
-- Tabla que normaliza el modelo: resuelve la relación muchos a muchos
-- entre T_LOTE_RECOLECCION y T_SUBPRODUCTO (un lote genera varios
-- subproductos y un subproducto se obtiene de varios lotes).
CREATE TABLE T_TRANSFORMACION_LOTE (
    FK_NRO_LOTE                NUMBER NOT NULL,
    FK_ID_SUBPRODUCTO          NUMBER NOT NULL,
    KG_OBTENIDOS               NUMBER(10,2) NOT NULL,
    CONSTRAINT PK_TRANSFORMACION_LOTE PRIMARY KEY (FK_NRO_LOTE, FK_ID_SUBPRODUCTO),
    CONSTRAINT FK_TRANSFORMACI_LOTE_RECOLECCI FOREIGN KEY (FK_NRO_LOTE)
        REFERENCES T_LOTE_RECOLECCION (NRO_LOTE),
    CONSTRAINT FK_TRANSFORMACI_SUBPRODUCTO FOREIGN KEY (FK_ID_SUBPRODUCTO)
        REFERENCES T_SUBPRODUCTO (ID_SUBPRODUCTO)
);

-- TABLA: T_CERTIFICADO_VALORIZACION
CREATE TABLE T_CERTIFICADO_VALORIZACION (
    NRO_CERTIFICADO            VARCHAR2(15) NOT NULL,
    FK_NRO_LOTE                NUMBER NOT NULL,
    FK_ID_PLANTA               NUMBER NOT NULL,
    FK_ID_PRODUCTOR            NUMBER NOT NULL,
    FECHA_EMISION              DATE NOT NULL,
    KG_VALORIZADOS             NUMBER(10,2) NOT NULL,
    KG_MERMA                   NUMBER(10,2) NOT NULL,
    TRATAMIENTO                VARCHAR2(25) NOT NULL,
    CONSTRAINT PK_CERTIFICADO_VALORIZACION PRIMARY KEY (NRO_CERTIFICADO),
    CONSTRAINT UN_CERTIFICADO_FK_NRO_LOTE UNIQUE (FK_NRO_LOTE),
    CONSTRAINT FK_CERTIFICADO_LOTE_RECOLECCIO FOREIGN KEY (FK_NRO_LOTE)
        REFERENCES T_LOTE_RECOLECCION (NRO_LOTE),
    CONSTRAINT FK_CERTIFICADO_PLANTA_RECICLAD FOREIGN KEY (FK_ID_PLANTA)
        REFERENCES T_PLANTA_RECICLADORA (ID_PLANTA),
    CONSTRAINT FK_CERTIFICADO_PRODUCTOR FOREIGN KEY (FK_ID_PRODUCTOR)
        REFERENCES T_PRODUCTOR (ID_PRODUCTOR),
    CONSTRAINT CK_CERTIFICADO_TRATAMIENTO
        CHECK (TRATAMIENTO IN ('Reciclaje', 'Valorizacion energetica')),
    CONSTRAINT CK_CERTIFICADO_KG_MERMA
        CHECK (KG_MERMA >= 0)
);


-- ============================================================
-- SECUENCIAS
