CREATE SEQUENCE SEQ_LOTE_RECOLECCION
    START WITH 5001
    INCREMENT BY 1
    NOCACHE;

-- Subproductos reciclados: inicia en 1, incrementa de 1 en 1
CREATE SEQUENCE SEQ_SUBPRODUCTO
    START WITH 1
    INCREMENT BY 1
    NOCACHE;


